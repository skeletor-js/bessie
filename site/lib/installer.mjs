export const installer = [
  '#!/bin/sh',
  'set -eu',
  'umask 077',
  '',
  'ARCHIVE_URL=https://github.com/skeletor-js/bessie/releases/download/v1.0.2/Bessie-1.0.2-23.zip',
  'EXPECTED_SHA256=e7782f0060395c6a0ab850e97d1bbdaf4478b001fee6323707220b7856423457',
  'DESTINATION=/Applications/Bessie.app',
  'STAGE=/Applications/.Bessie.app.install-$$',
  'TMP_BASE=${TMPDIR:-/tmp}',
  'WORK=$(mktemp -d "$TMP_BASE/bessie-install.XXXXXX")',
  'BACKUP=$WORK/Bessie.app.backup',
  'ARCHIVE=$WORK/Bessie.zip',
  'EXTRACTED=$WORK/extracted',
  'installed_new=0',
  '',
  'fail() {',
  '  printf "Bessie install failed: %s\\n" "$1" >&2',
  '  exit 1',
  '}',
  '',
  'cleanup() {',
  '  status=$?',
  '  trap - EXIT HUP INT TERM',
  '  if [ "$status" -ne 0 ]; then',
  '    if [ "$installed_new" -eq 1 ] && [ -e "$DESTINATION" ]; then',
  '      rm -rf "$DESTINATION"',
  '    fi',
  '    if [ -e "$BACKUP" ] && [ ! -e "$DESTINATION" ]; then',
  '      mv "$BACKUP" "$DESTINATION"',
  '    fi',
  '  fi',
  '  [ ! -e "$STAGE" ] || rm -rf "$STAGE"',
  '  [ ! -e "$WORK" ] || rm -rf "$WORK"',
  '  exit "$status"',
  '}',
  'trap cleanup EXIT HUP INT TERM',
  '',
  '[ "$(uname -s)" = Darwin ] || fail "macOS is required"',
  '[ "$(uname -m)" = arm64 ] || fail "Apple silicon is required"',
  'major=$(sw_vers -productVersion | cut -d. -f1)',
  '[ "$major" -ge 14 ] || fail "macOS 14 or newer is required"',
  '[ -w /Applications ] || fail "/Applications is not writable; use the direct download instead: $ARCHIVE_URL"',
  'for tool in curl shasum ditto codesign xcrun spctl osascript open; do',
  '  command -v "$tool" >/dev/null 2>&1 || fail "required tool is missing: $tool"',
  'done',
  '[ ! -e "$STAGE" ] || fail "temporary install path already exists: $STAGE"',
  '',
  'printf "Downloading Bessie 1.0.2...\\n"',
  'curl --proto "=https" --tlsv1.2 -fL "$ARCHIVE_URL" -o "$ARCHIVE"',
  'actual_sha=$(shasum -a 256 "$ARCHIVE" | cut -d" " -f1)',
  '[ "$actual_sha" = "$EXPECTED_SHA256" ] || fail "archive checksum did not match"',
  '',
  'mkdir "$EXTRACTED"',
  'ditto -x -k "$ARCHIVE" "$EXTRACTED"',
  'CANDIDATE=$EXTRACTED/Bessie.app',
  '[ -d "$CANDIDATE" ] || fail "archive does not contain Bessie.app"',
  'codesign --verify --deep --strict "$CANDIDATE" || fail "Developer ID signature verification failed"',
  'xcrun stapler validate "$CANDIDATE" || fail "notarization ticket validation failed"',
  'spctl --assess --type execute "$CANDIDATE" || fail "Gatekeeper rejected Bessie.app"',
  'ditto "$CANDIDATE" "$STAGE"',
  '',
  'if [ -e "$DESTINATION" ]; then',
  '  osascript -e "tell application id \\"dev.bessie.app\\" to quit" >/dev/null 2>&1 || true',
  '  attempts=0',
  '  while pgrep -f "^/Applications/Bessie.app/Contents/MacOS/BessieApp$" >/dev/null 2>&1; do',
  '    attempts=$((attempts + 1))',
  '    [ "$attempts" -lt 40 ] || fail "the running Bessie app did not quit"',
  '    sleep 0.25',
  '  done',
  '  mv "$DESTINATION" "$BACKUP"',
  'fi',
  '',
  'mv "$STAGE" "$DESTINATION"',
  'installed_new=1',
  'codesign --verify --deep --strict "$DESTINATION" || fail "installed signature verification failed"',
  'xcrun stapler validate "$DESTINATION" || fail "installed notarization ticket validation failed"',
  'spctl --assess --type execute "$DESTINATION" || fail "Gatekeeper rejected the installed app"',
  'open "$DESTINATION"',
  '[ ! -e "$BACKUP" ] || rm -rf "$BACKUP"',
  'installed_new=0',
  'printf "Installed Bessie 1.0.2 in /Applications.\\n"',
].join('\n') + '\n';
